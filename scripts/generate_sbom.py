"""Generate the phase-0 SBOM and the third-party notices file (day 10).

Run from the repository root:

    uv run python scripts/generate_sbom.py
    uv run python scripts/generate_sbom.py --output build/sbom.json --notices THIRD_PARTY_NOTICES.md

The SBOM is CycloneDX 1.5 JSON built from the same licence collector the gate
uses, so a package cannot be in the SBOM with a licence the gate has not seen.
"""

from __future__ import annotations

import argparse
import json
import uuid
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import quote

from licensing import ROOT, all_components

PROJECT_NAME = "almahmoud-erp"
PROJECT_VERSION = "0.1.0"


def _purl(scope: str, name: str, version: str) -> str:
    if scope == "python":
        normalised = name.lower().replace("_", "-")
        return f"pkg:pypi/{quote(normalised, safe='')}@{quote(version, safe='')}"
    if name.startswith("@") and "/" in name:
        namespace, package = name.split("/", 1)
        return (
            f"pkg:npm/{quote(namespace, safe='')}/{quote(package, safe='')}"
            f"@{quote(version, safe='')}"
        )
    return f"pkg:npm/{quote(name, safe='')}@{quote(version, safe='')}"


def build_sbom(timestamp: str) -> dict[str, object]:
    components, exceptions_used, problems = all_components()
    if problems:
        raise SystemExit("refusing to build an SBOM with unknown licences: " + "; ".join(problems))
    serial = uuid.uuid5(uuid.NAMESPACE_URL, f"{PROJECT_NAME}@0.1.0/{timestamp}")
    bom_components: list[dict[str, object]] = []
    for component in components:
        borrowed = _purl(component.scope, component.name, component.version)
        bom_components.append(
            {
                "type": "library",
                "bom-ref": borrowed,
                "name": component.name,
                "version": component.version,
                "purl": borrowed,
                "licenses": [{"expression": component.expression}],
                "properties": [
                    {"name": "almahmoud:scope", "value": component.scope},
                    {"name": "almahmoud:source", "value": component.source},
                ],
            }
        )
    return {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "serialNumber": f"urn:uuid:{serial}",
        "version": 1,
        "metadata": {
            "timestamp": timestamp,
            "tools": {
                "components": [
                    {"type": "application", "name": "generate_sbom.py", "version": "0.1.0"}
                ]
            },
            "component": {
                "type": "application",
                "bom-ref": "pkg:pypi/almahmoud-erp@0.1.0",
                "name": PROJECT_NAME,
                "version": PROJECT_VERSION,
            },
            "properties": [
                {"name": "almahmoud:licence-exceptions", "value": ", ".join(exceptions_used) or "none"}
            ],
        },
        "components": bom_components,
    }


def build_notices(timestamp: str) -> str:
    components, exceptions_used, problems = all_components()
    if problems:
        raise SystemExit("refusing to write notices with unknown licences: " + "; ".join(problems))
    grouped: dict[str, list[str]] = defaultdict(list)
    for component in components:
        grouped[component.expression].append(
            f"- {component.name} {component.version} ({component.scope})"
        )
    lines = [
        "# Third-party notices",
        "",
        "<!-- Generated by scripts/generate_sbom.py; edit the script, not this file. -->",
        "",
        f"Generated: {timestamp}",
        "",
        "The Al-Mahmoud ERP phase-0 build uses the following third-party packages. All",
        "are unmodified upstream distributions. The full machine-readable inventory",
        "is build/sbom.json (CycloneDX 1.5); the licence gate is",
        "scripts/check_licences.py.",
        "",
        "Case-by-case licences allowed by",
        "docs/09-decisions/0002-phase-0-licence-exceptions.md:",
        "",
    ]
    for exception in exceptions_used:
        lines.append(f"- {exception}")
    if not exceptions_used:
        lines.append("- none")
    lines.append("")
    for expression in sorted(grouped):
        lines.append(f"## {expression}")
        lines.append("")
        lines.extend(sorted(grouped[expression]))
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the CycloneDX SBOM and third-party notices")
    parser.add_argument("--output", type=Path, default=ROOT / "build" / "sbom.json")
    parser.add_argument("--notices", type=Path, default=ROOT / "THIRD_PARTY_NOTICES.md")
    args = parser.parse_args()

    timestamp = datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    sbom = build_sbom(timestamp)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(sbom, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    args.notices.write_text(build_notices(timestamp), encoding="utf-8")
    components = sbom["components"]
    assert isinstance(components, list)
    print(f"sbom-ok: {len(components)} components -> {args.output}")
    print(f"notices-ok -> {args.notices}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
